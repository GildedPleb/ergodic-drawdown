/** Pure renderer for src/v2/design/tokens/tokens.ts (output is already oxfmt-formatted). */

export const TOKEN_CSS_FILES = [
  "motion-etc.css",
  "palette.css",
  "semantic.css",
  "space.css",
  "type.css",
] as const;

export const collectNames = (cssTexts: readonly string[]): string[] => {
  const names = new Set<string>();
  for (const text of cssTexts) {
    const bare = text.replace(/\/\*[\s\S]*?\*\//g, "");
    for (const match of bare.matchAll(/--([a-z0-9-]+)\s*:/gi)) {
      if (match[1] !== undefined) names.add(match[1]);
    }
  }
  return [...names].toSorted();
};

export const renderTokens = (cssTexts: readonly string[]): string => {
  const sorted = collectNames(cssTexts);
  const space = sorted
    .map((n) => /^s-(\d+)$/.exec(n)?.[1])
    .filter((n): n is string => n !== undefined)
    .toSorted((a, b) => Number(a) - Number(b));
  return [
    "/* GENERATED by scripts/v2/generate-tokens.ts — do not edit. */",
    "",
    "export const tokenNames = [",
    ...sorted.map((n) => `  ${JSON.stringify(n)},`),
    "] as const;",
    "",
    "export type TokenName = (typeof tokenNames)[number];",
    "",
    "/** Steps of the --s-* space scale. Layout `gap` props are typed to this (ADR R6). */",
    `export const space = [${space.map((n) => JSON.stringify(n)).join(", ")}] as const;`,
    "",
    "export type Space = (typeof space)[number];",
    "",
    "export const token = <K extends TokenName>(name: K): `var(--${K})` => `var(--${name})`;",
    "",
    "export const tokens = {",
    ...sorted.map((n) => `  ${/^[a-z]\w*$/.test(n) ? n : JSON.stringify(n)}: "var(--${n})",`),
    "} as const;",
    "",
  ].join("\n");
};
