/** Generate src/v2/design/tokens/tokens.ts from Form CSS custom properties. */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensDir = join(here, "../../src/v2/design/tokens");
const outPath = join(tokensDir, "tokens.ts");

const cssFiles = readdirSync(tokensDir)
  .filter((f) => f.endsWith(".css") && f !== "index.css")
  .toSorted();

const names = new Set<string>();
const propRe = /--([a-z0-9-]+)\s*:/gi;
for (const file of cssFiles) {
  const text = readFileSync(join(tokensDir, file), "utf8");
  for (const match of text.matchAll(propRe)) {
    const name = match[1];
    if (name !== undefined) names.add(name);
  }
}

const sorted = [...names].toSorted();
const entries = sorted.map((n) => `  ${JSON.stringify(n)}: "var(--${n})",`).join("\n");
const lines = [
  "/* GENERATED by scripts/v2/generate-tokens.ts — do not edit. */",
  "",
  "export const tokenNames = [",
  ...sorted.map((n) => `  ${JSON.stringify(n)},`),
  "] as const;",
  "",
  "export type TokenName = (typeof tokenNames)[number];",
  "",
  "export const token = <K extends TokenName>(name: K): `var(--${K})` => `var(--${name})`;",
  "",
  "export const tokens = {",
  entries,
  "} as const;",
  "",
];
writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${outPath} (${sorted.length} tokens)`);
